import { agent, deploy, guestJoin, partnerJoin, ok, refused, eq, finish, NODE } from './lib.mjs';
const C = 'GlokiEngageCommunity';
console.log('GlokiEngageCommunity');
const a = await agent();
const id = await deploy(a, C, { name: 'Climate', description: 'd', node: NODE, profile: 'pa' });
await ok('details', async () => { const d = await a.read(id, 'get_details'); eq(d.name, 'Climate'); eq(d.createdBy, a.agent); });
await ok('founder is a member', async () => eq((await a.read(id, 'get_members')).map((m) => m.agent), [a.agent]));
const b = await agent();
await ok('b joins as a partner', async () => eq((await partnerJoin(b, a, id, C)).reply, true));
await ok('b enrolls', () => b.write(id, 'enroll', { node: NODE, profile: 'pb' }));
const c = await agent();
await ok('c joins as a guest', async () => eq((await guestJoin(c, a, id, C)).reply, true));
await refused('c cannot add an initiative before enrolling', 'Only members', () => c.write(id, 'add_initiative', { node: NODE, contract_id: '0x1' }));
await ok('c enrolls (a guest member)', () => c.write(id, 'enroll', { node: NODE, profile: 'pc' }));
await ok('members', async () => eq((await a.read(id, 'get_members')).map((m) => m.profile), ['pa', 'pb', 'pc']));
await ok('c adds an initiative, as itself', async () => { await c.write(id, 'add_initiative', { node: NODE, contract_id: '0xabc' }); const list = await b.read(id, 'get_initiatives'); eq(list[0].agent, c.agent); eq(list[0].contract_id, '0xabc'); });
await refused('only the founder edits', 'Only the founder', () => b.write(id, 'set_details', { name: 'x', description: 'y' }));
await ok('founder edits', () => a.write(id, 'set_details', { name: 'Climate 2', description: 'y' }));
await ok('a partner sees it', async () => eq((await b.read(id, 'get_details')).name, 'Climate 2'));
finish(a, b, c);
