import { agent, deploy, guestJoin, ok, refused, eq, finish, Ibc, NODE } from './lib.mjs';
const F = 'Forum';
console.log('Forum');
const app = await agent();
const id = await deploy(app, F);
await app.setPublic(id, true);
const a = await agent(), b = await agent();
for (const p of [a, b]) await guestJoin(p, app, id, F);
const pub = (m) => Ibc.publicRead(NODE, app.agent, id, m);
const post = (who, text, parent, profile) => who.write(id, 'add_comment', { text, parent_id: parent, category: '', sources: '[]', node: NODE, profile });
const root = await ok('a posts (returns its id)', () => post(a, 'hello', 0, 'pa'));
await ok('b replies', () => post(b, 'hi', root, 'pb'));
await ok('each author is a participant, with their profile', async () => eq((await pub('get_participants')).map((p) => [p.agent, p.profile]), [[a.agent, 'pa'], [b.agent, 'pb']]));
await ok('a later post updates the author\'s profile', async () => { await post(a, 'again', 0, 'pa2'); eq((await pub('get_participants')).length, 2); eq((await pub('get_participants'))[0].profile, 'pa2'); });
await refused('reply to an unknown post', 'Unknown comment', () => post(b, 'x', 99, 'pb'));
await ok('like toggles', async () => { await b.write(id, 'like_comment', { comment_id: root }); await a.write(id, 'like_comment', { comment_id: root }); await b.write(id, 'like_comment', { comment_id: root }); eq((await pub('get_comments'))[0].likes, [a.agent]); });
await ok('votes on roots', async () => { await b.write(id, 'vote_comment', { comment_id: root, direction: 'up' }); eq((await pub('get_comment_votes')).length, 1); });
await refused('vote on a reply', 'Only a root comment', () => a.write(id, 'vote_comment', { comment_id: 2, direction: 'up' }));
await refused('delete someone else\'s post', 'Only the author can delete', () => b.write(id, 'delete_comment', { comment_id: root }));
await ok('delete own post', async () => { await a.write(id, 'delete_comment', { comment_id: root }); const c = (await pub('get_comments'))[0]; eq(c.deleted, true); eq(c.text, ''); });
const s = await agent();
await refused('a stranger cannot post without joining', 'no contract', () => post(s, 'x', 0, ''));
finish(app, a, b, s);
